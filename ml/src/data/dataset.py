"""Dataset wrappers built from generated split CSV manifests.

Training and evaluation scripts in this project do not scan the raw dataset
folders directly. Instead they consume split CSVs so experiments are
reproducible and the exact train/validation/test membership is easy to inspect.
"""

from pathlib import Path

import pandas as pd
from PIL import Image
from torch.utils.data import Dataset


class PlantVillageSplitDataset(Dataset):
    """PyTorch dataset backed by a generated split CSV.

    Each row in the CSV is expected to contain an absolute image path and the
    corresponding integer class index. This keeps class ordering synchronized
    with ``classes.txt`` and downstream model heads.
    """

    def __init__(self, csv_path: str, transform=None):
        """Load the split manifest into memory.

        Args:
            csv_path: Path to a split CSV generated by ``split_data.py``.
            transform: Optional torchvision transform pipeline applied to each
                loaded image.
        """
        self.df = pd.read_csv(csv_path)
        self.transform = transform

    def __len__(self):
        """Return the number of examples in the split."""
        return len(self.df)

    def __getitem__(self, idx: int):
        """Load one image and its class index.

        Args:
            idx: Row index in the split dataframe.

        Returns:
            A tuple of ``(image, label_index)`` where the image has been
            transformed if a transform pipeline was provided.
        """
        row = self.df.iloc[idx]
        img = Image.open(Path(row["image_path"])).convert("RGB")
        label = int(row["label_idx"])
        if self.transform:
            img = self.transform(img)
        return img, label
